def primary_category_counts(parsed):
    """How many documents have each category as their top (highest
    probability) pick. Shared by the bar chart and the token-length panel
    so both agree on which categories are "top" and in what order."""
    counter = Counter()
    for p in parsed:
        name, _ = top_category(p)
        if name:
            counter[name] += 1
    return counter


def plot_top_categories(parsed, ax, top_n=10):
    counter = primary_category_counts(parsed)
    common = counter.most_common(top_n)
    if not common:
        ax.axis("off")
        return
    names, counts = zip(*common)
    y = range(len(names))
    ax.barh(y, counts, color="#4C72B0")
    ax.set_yticks(y)
    ax.set_yticklabels(names)
    ax.invert_yaxis()
    ax.set_xlabel("Document count")
    ax.set_title("Top primary categories")


def plot_confidence_distribution(parsed, ax):
    counter = Counter(p["confidence"] for p in parsed)
    order = [c for c in CONFIDENCE_ORDER if c in counter]
    order += [c for c in counter if c not in CONFIDENCE_ORDER]
    counts = [counter[c] for c in order]
    colors = [CONFIDENCE_COLORS.get(c, "#999999") for c in order]
    ax.bar(order, counts, color=colors)
    ax.set_title("Confidence distribution")
    ax.set_ylabel("Document count")


def plot_difficulty_distribution(parsed, ax):
    counter = Counter(p["difficulty"] for p in parsed)
    order = [d for d in DIFFICULTY_ORDER if d in counter]
    order += [d for d in counter if d not in DIFFICULTY_ORDER]
    counts = [counter[d] for d in order]
    ax.bar(order, counts, color="#7B6D8D")
    ax.set_title("Difficulty distribution")
    ax.set_ylabel("Document count")
    ax.tick_params(axis="x", rotation=20)


def plot_prior_knowledge_vs_difficulty(parsed, ax):
    diff_x = {d: i for i, d in enumerate(DIFFICULTY_ORDER)}
    rng = np.random.default_rng(0)

    for p in parsed:
        if p["prior_knowledge"] is None or p["difficulty"] not in diff_x:
            continue
        x = diff_x[p["difficulty"]] + rng.uniform(-0.15, 0.15)
        y = p["prior_knowledge"]
        color = CONFIDENCE_COLORS.get(p["confidence"], "#999999")
        ax.scatter(x, y, color=color, alpha=0.75, s=45,
                   edgecolor="white", linewidth=0.5)

    ax.set_xticks(range(len(DIFFICULTY_ORDER)))
    ax.set_xticklabels(DIFFICULTY_ORDER, rotation=20)
    ax.set_ylim(-0.05, 1.05)
    ax.set_ylabel("Prior knowledge")
    ax.set_title("Prior knowledge vs. difficulty\n(color = confidence)")

    handles = [mpatches.Patch(color=c, label=l) for l, c in CONFIDENCE_COLORS.items()]
    ax.legend(handles=handles, title="Confidence", fontsize=8, loc="upper right")


def plot_category_probability_box(parsed, ax, max_ranks=5):
    """Box-plots probability by rank (rank 0 = each doc's top category,
    rank 1 = second, etc.), since documents may not all carry the same
    number of categories anymore."""
    max_present = max((len(p["categories"]) for p in parsed), default=0)
    n_ranks = min(max_present, max_ranks)

    data, labels = [], []
    for rank in range(n_ranks):
        vals = [prob for p in parsed
                for _, prob in [category_at_rank(p, rank)] if prob is not None]
        if vals:
            data.append(vals)
            labels.append(f"rank {rank + 1}")

    if not data:
        ax.axis("off")
        return
    try:
        ax.boxplot(data, tick_labels=labels)  # matplotlib >= 3.9
    except TypeError:
        ax.boxplot(data, labels=labels)  # matplotlib < 3.9
    ax.set_ylabel("Probability")
    ax.set_title("Probability spread by category rank\n(rank 1 = each doc's top category)")


def plot_tokens_by_category(parsed, ax, top_n=10):
    """Box-plots document length (tokens) for each of the most common
    primary categories, so you can see e.g. whether "history" articles run
    much longer than "mathematics" articles. Uses the same top-N category
    selection/order as plot_top_categories for easy cross-reference."""
    counter = primary_category_counts(parsed)
    top_names = [name for name, _ in counter.most_common(top_n)]

    # Precompute (top category, tokens) once per doc rather than re-deriving
    # top_category() inside a nested loop over every candidate category.
    doc_top_tokens = [(top_category(p)[0], p["tokens"]) for p in parsed]

    data, labels = [], []
    for name in top_names:
        vals = [tok for cat, tok in doc_top_tokens if cat == name and tok is not None]
        if vals:
            data.append(vals)
            labels.append(name)

    if not data:
        ax.axis("off")
        return
    try:
        ax.boxplot(data, tick_labels=labels, vert=False)  # matplotlib >= 3.9
    except TypeError:
        ax.boxplot(data, labels=labels, vert=False)  # matplotlib < 3.9
    ax.invert_yaxis()  # largest/most common category on top, matching the bar chart
    ax.set_xlabel("Tokens (document length)")
    ax.set_title(f"Document length by top {len(labels)} categories")


def plot_summary_text(parsed, ax):
    ax.axis("off")
    n = len(parsed)
    avg_pk = np.mean([p["prior_knowledge"] for p in parsed if p["prior_knowledge"] is not None])
    avg_tokens = np.mean([p["tokens"] for p in parsed if p["tokens"] is not None])
    n_categories = len({top_category(p)[0] for p in parsed if top_category(p)[0]})
    lines = [
        f"Documents: {n}",
        f"Distinct primary categories: {n_categories}",
        f"Avg. prior knowledge: {avg_pk:.2f}" if not np.isnan(avg_pk) else "Avg. prior knowledge: n/a",
        f"Avg. tokens: {avg_tokens:.0f}" if not np.isnan(avg_tokens) else "Avg. tokens: n/a",
    ]
    ax.text(0.05, 0.8, "\n".join(lines), fontsize=12, va="top",
            family="monospace", transform=ax.transAxes)
    ax.set_title("Summary")


