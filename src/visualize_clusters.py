def main():
    parser = argparse.ArgumentParser(description="Visualize document cluster JSON")
    parser.add_argument("json_path", help="Path to input JSON (array, single object, or JSON-lines)")
    parser.add_argument("--out", default="cluster_dashboard.png", help="Output image path")
    args = parser.parse_args()

    records = load_records(args.json_path)
    parsed = parse_records(records)

    if not parsed:
        raise SystemExit("No records found in the input file.")

    build_dashboard(parsed, args.out)


if __name__ == "__main__":
    main()