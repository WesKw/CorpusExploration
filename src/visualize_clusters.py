import argparse
import json
from collections import Counter

import matplotlib.patches as mpatches
import matplotlib.pyplot as plt
import numpy as np

CONFIDENCE_ORDER = ["low", "medium", "high"]
DIFFICULTY_ORDER = ["beginner", "intermediate", "advanced", "expert"]

CONFIDENCE_COLORS = {"low": "#E07B54", "medium": "#F2C14E", "high": "#5B8C5A"}

# Every other key on a record is treated as "<category_name>": "<probability>"
RESERVED_KEYS = {"title", "confidence", "difficulty", "prior_knowledge", "tokens"}


# ---------------------------------------------------------------------------
# Loading & parsing
# ---------------------------------------------------------------------------

def load_records(path):
    """Load records from a JSON array, a single JSON object, or JSON-lines."""
    with open(path, "r", encoding="utf-8") as f:
        text = f.read().strip()

    try:
        data = json.loads(text)
        if isinstance(data, dict):
            return [data]
        if isinstance(data, list):
            return data
    except json.JSONDecodeError:
        pass

    # Fall back to JSON-lines (one object per line)
    records = []
    for line in text.splitlines():
        line = line.strip()
        if line:
            records.append(json.loads(line))
    return records


def parse_probability(value):
    """Coerce a probability field (often a string) into a float, or None."""
    if value is None or value == "":
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def parse_int(value):
    """Coerce a count field (often a string, sometimes "1234.0") into an
    int, or None."""
    if value is None or value == "":
        return None
    try:
        return int(float(value))
    except (TypeError, ValueError):
        return None


def parse_records(records):
    """Turn raw JSON records into a flat list of dicts ready for plotting.

    Each result has a "categories" dict of {category_name: probability},
    sorted from most to least probable, so "rank 0" is always the
    document's primary category regardless of how many it has."""
    parsed = []
    for r in records:
        item = {
            "title": r.get("title", "Untitled"),
            "confidence": (r.get("confidence") or "unknown").lower(),
            "difficulty": (r.get("difficulty") or "unknown").lower(),
            "prior_knowledge": parse_probability(r.get("prior_knowledge")),
            "tokens": parse_int(r.get("tokens")),
        }

        categories = {}
        for key, value in r.items():
            if key in RESERVED_KEYS:
                continue
            prob = parse_probability(value)
            # key categories should all have the same formatting to avoid issues
            if prob is not None:
                categories[key.lower()] = prob

        item["categories"] = dict(
            sorted(categories.items(), key=lambda kv: kv[1], reverse=True)
        )
        parsed.append(item)
    return parsed


def category_at_rank(item, rank):
    """Return (name, probability) for the rank-th most probable category
    on this document (rank 0 = highest probability), or (None, None)."""
    entries = list(item["categories"].items())
    if rank < len(entries):
        return entries[rank]
    return None, None


def top_category(item):
    """Convenience wrapper: a document's single most probable category."""
    return category_at_rank(item, 0)


