def build_dashboard(parsed, out_path):
    fig, axes = plt.subplots(3, 3, figsize=(20, 14))

    plot_top_categories(parsed, axes[0, 0])
    plot_confidence_distribution(parsed, axes[0, 1])
    plot_difficulty_distribution(parsed, axes[0, 2])
