def plot_category_probability_box(parsed, ax, max_ranks=5):
    """Box-plots probability by rank (rank 0 = each doc's top category,
    rank 1 = second, etc.), since documents may not all carry the same
    number of categories anymore."""
    max_present = max((len(p["categories"]) for p in parsed), default=0)
    n_ranks = min(max_present, max_ranks)

    data, labels = [], []
    for rank in range(n_ranks):
        vals = [prob for p in parsed
                for _, prob in [category_at_rank(p, rank)] if prob is not None]
        if vals:
            data.append(vals)
            labels.append(f"rank {rank + 1}")

    if not data:
        ax.axis("off")
        return
    try:
        ax.boxplot(data, tick_labels=labels)  # matplotlib >= 3.9
    except TypeError:
        ax.boxplot(data, labels=labels)  # matplotlib < 3.9
    ax.set_ylabel("Probability")
    ax.set_title("Probability spread by category rank\n(rank 1 = each doc's top category)")


def plot_tokens_by_category(parsed, ax, top_n=10):
    """Box-plots document length (tokens) for each of the most common
    primary categories, so you can see e.g. whether "history" articles run
    much longer than "mathematics" articles. Uses the same top-N category
    selection/order as plot_top_categories for easy cross-reference."""
    counter = primary_category_counts(parsed)
    top_names = [name for name, _ in counter.most_common(top_n)]

    # Precompute (top category, tokens) once per doc rather than re-deriving
    # top_category() inside a nested loop over every candidate category.
    doc_top_tokens = [(top_category(p)[0], p["tokens"]) for p in parsed]

    data, labels = [], []
    for name in top_names:
        vals = [tok for cat, tok in doc_top_tokens if cat == name and tok is not None]
        if vals:
            data.append(vals)
            labels.append(name)

    if not data:
        ax.axis("off")
        return
    try:
        ax.boxplot(data, tick_labels=labels, vert=False)  # matplotlib >= 3.9
    except TypeError:
        ax.boxplot(data, labels=labels, vert=False)  # matplotlib < 3.9
    ax.invert_yaxis()  # largest/most common category on top, matching the bar chart
    ax.set_xlabel("Tokens (document length)")
    ax.set_title(f"Document length by top {len(labels)} categories")


def plot_difficulty_by_category(parsed, ax, top_n=10):
    """100%-stacked horizontal bars: for each of the most common primary
    categories, what share of its documents are beginner/intermediate/
    advanced/expert. Normalized per-category (each bar sums to 100%)
    rather than raw counts, since the question is "what's the difficulty
    mix *within* this category", not how many documents it has overall
    (that's already covered by plot_top_categories). Uses the same top-N
    category selection/order as plot_top_categories for cross-reference."""
    counter = primary_category_counts(parsed)
    top_names = [name for name, _ in counter.most_common(top_n)]

    doc_top_difficulty = [(top_category(p)[0], p["difficulty"]) for p in parsed]

    rows = []
    for name in top_names:
        diffs = [d for cat, d in doc_top_difficulty if cat == name]
        if not diffs:
            continue
        diff_counts = Counter(diffs)
        total = len(diffs)
        shares = [diff_counts.get(d, 0) / total for d in DIFFICULTY_ORDER]
        rows.append((name, shares, total))

    if not rows:
        ax.axis("off")
        return

    names = [r[0] for r in rows]
    totals = [r[2] for r in rows]
    y = np.arange(len(names))
    left = np.zeros(len(names))
    for i, d in enumerate(DIFFICULTY_ORDER):
        widths = np.array([r[1][i] for r in rows])
        ax.barh(y, widths, left=left, color=DIFFICULTY_COLORS.get(d, "#999999"),
                label=d, height=0.7)
        left += widths

    for yi, total in zip(y, totals):
        ax.text(1.02, yi, f"n={total}", va="center", fontsize=7, transform=ax.get_yaxis_transform())

    ax.set_yticks(y)
    ax.set_yticklabels(names)
    ax.invert_yaxis()
    ax.set_xlim(0, 1)
    ax.set_xlabel("Share of documents")
    ax.set_title(f"Difficulty mix within top {len(names)} categories")
    ax.legend(title="Difficulty", fontsize=7, loc="lower left",
              bbox_to_anchor=(0, -0.32), ncol=4, framealpha=0.9)


def plot_quality_metrics_by_category(parsed, ax, top_n=10):
    """Grouped box plots of prior_knowledge, vocab_complexity, and
    sentence_quality for each of the top-N primary categories, so these
    three continuous quality signals can be compared side by side across
    a handful of the most common topics. Uses the same top-N category
    selection/order as plot_top_categories for cross-reference."""
    counter = primary_category_counts(parsed)
    top_names = [name for name, _ in counter.most_common(top_n)]

    metrics = [
        ("prior_knowledge", "#4C72B0"),
        ("vocab_complexity", "#DD8452"),
        ("sentence_quality", "#55A868"),
    ]
    box_width = 0.8 / len(metrics)

    doc_top = [(top_category(p)[0], p) for p in parsed]

    present_names = []
    data_by_metric = {m: [] for m, _ in metrics}
    positions_by_metric = {m: [] for m, _ in metrics}
    for name in top_names:
        docs = [p for cat, p in doc_top if cat == name]
        if not docs:
            continue
        base = len(present_names)
        present_names.append(name)
        for mi, (metric, _) in enumerate(metrics):
            vals = [p[metric] for p in docs if p[metric] is not None]
            data_by_metric[metric].append(vals)
            offset = (mi - (len(metrics) - 1) / 2) * box_width
            positions_by_metric[metric].append(base + offset)

    if not present_names:
        ax.axis("off")
        return

    for metric, color in metrics:
        pairs = [(vals, pos) for vals, pos in
                 zip(data_by_metric[metric], positions_by_metric[metric]) if vals]
        if not pairs:
            continue
        vals, positions = zip(*pairs)
        bp = ax.boxplot(vals, positions=positions, widths=box_width * 0.85,
                         patch_artist=True, showfliers=False)
        for box in bp["boxes"]:
            box.set_facecolor(color)
            box.set_alpha(0.7)
        for median in bp["medians"]:
            median.set_color("black")

    ax.set_xticks(range(len(present_names)))
    ax.set_xticklabels(present_names, rotation=45, ha="right")
    ax.set_xlim(-0.6, len(present_names) - 0.4)
    ax.set_ylim(-0.05, 1.05)
    ax.set_ylabel("Score")
    ax.set_title(f"Quality metric spread across top {len(present_names)} categories")

    handles = [mpatches.Patch(color=c, label=m.replace("_", " ")) for m, c in metrics]
    ax.legend(handles=handles, fontsize=7, loc="upper right")


def plot_summary_text(parsed, ax, fig):
    ax.axis("off")
    n = len(parsed)
    avg_pk = np.mean([p["prior_knowledge"] for p in parsed if p["prior_knowledge"] is not None])
    avg_tokens = np.mean([p["tokens"] for p in parsed if p["tokens"] is not None])
    n_categories = len({top_category(p)[0] for p in parsed if top_category(p)[0]})
    lines = [
        f"Documents: {n}",
        f"Distinct primary categories: {n_categories}",
        f"Avg. prior knowledge: {avg_pk:.2f}" if not np.isnan(avg_pk) else "Avg. prior knowledge: n/a",
        f"Avg. tokens: {avg_tokens:.0f}" if not np.isnan(avg_tokens) else "Avg. tokens: n/a",
    ]
    # ax.text(0.05, 0.8, "\n".join(lines), fontsize=12, va="top",
            # family="monospace", transform=ax.transAxes)
    fig.supxlabel(' | '.join(lines))
    ax.set_title("Summary")


